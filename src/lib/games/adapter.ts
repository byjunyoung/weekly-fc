// src/lib/games/adapter.ts — 모든 게임이 지키는 약속(2026-11-07). 순수 — 화면·시계·난수 함수·네트워크를 모른다.
// 설계: docs/superpowers/specs/2026-11-07-games-program-design.md §2
//
// 사용자: "자유 훈련장, 여러 드리블 훈련장, 승부차기, 프리킥 같은 게임 만들어서 온라인 가능하게 하자. 다 2d, 3d 모드 별로 가능하게 하고."
// 게임이 열 개(다섯 × 모드 둘)가 되면 온라인 세션을 열 번 짤 수 없다. 그래서 세션(방장 계산·스냅샷·손님 예측)·메시지 검사·예측기는
// 이 약속만 보고 돌고, 게임 하나는 "어댑터(계산) + 화면(src/react/game/views)" 둘로 끝나게 한다.
//
// 지키는 선(온라인 스펙 2026-11-06 §2.4·§2.5 를 모든 게임으로 넓힌 것):
//   - step 은 순수·결정적. 같은 상태 + 같은 입력이면 어느 브라우저에서나 같은 결과 — 삼각함수·시계·난수 함수 금지(씨앗은 상태 안).
//   - 상태·설정은 JSON 으로 그대로 오가는 값만(함수·클래스·Map 없음). 방장이 보낸 그대로 손님이 step 을 이어 돌린다.
//   - 입력은 정수 하나로 양자화한다(encode/decode). 방장·봇·손님·예측이 모두 그 정수를 풀어 쓴 값으로 계산해야 예측이 덜 어긋난다.
//
// 멤버는 세션이 실제로 쓰는 것만 둔다. 각 멤버 위의 주석이 "누가 왜 쓰나"다.

/** 모든 게임은 60틱(1/60초)으로 돈다 — 세션의 고정 틱 루프·스냅샷 주기(6틱 = 초당 10번)가 이 값 하나를 쓴다. */
export const TICK_HZ = 60;

/** 몸 하나의 위치(그리기용 부드럽게 하기가 읽고 쓰는 것). 나머지 필드는 그대로 따라간다. */
export type Point = { x: number; y: number };

export type GameAdapter<C, S, I> = {
  /** 게임 종류 — 'match2d' | 'penalty2d' | … 방 설정·start 메시지·목록 카드가 이 값으로 게임을 찾는다. */
  id: string;
  /** 첫 상태. seed 는 상태 안에 넣어 step 이 그 씨앗으로만 난수를 뽑게 한다. */
  create(config: C, seed: number): S;
  /** 한 틱. inputs[i] = i 번 자리의 입력(길이 = slots(config)). 받은 상태를 바꾸지 않고 새 상태를 돌려준다. */
  step(state: S, config: C, inputs: I[]): S;
  /** 손을 뗀 입력 — 빈자리·끊긴 손님·예측의 모자란 자리. */
  idle: I;
  /** 입력 → 정수(0 ≤ q < codes). 방장·손님이 같은 정수를 풀어 쓰게(전송·예측). */
  encode(i: I): number;
  /** 정수 → 입력. 범위 밖·정수 아님은 idle(바깥에서 온 값이라). */
  decode(q: number): I;
  /** 입력 정수의 가짓수. 메시지 검사(in·snap 의 입력)가 범위를 이 값으로 자른다. */
  codes: number;
  /** 바깥(채널)에서 온 설정의 모양 검사 — start 메시지. */
  okConfig(c: unknown): c is C;
  /** 바깥에서 온 상태의 모양 검사 — snap 메시지. config 를 받는 이유: 자리 수·id 범위처럼 설정과 맞아야 하는 것까지 본다
   *  (모양이 어긋난 상태를 예측기·그리기가 받으면 프레임마다 예외를 던진다). */
  okState(s: unknown, config: C): s is S;
  /** 지금 틱 — 스냅샷 순서(낮은 틱 버림)와 소리 비교(틱이 뒤로 가면 새 판)에 쓴다. */
  tick(s: S): number;
  /** 끝났나 — 방장은 결과를 띄우고 4초 뒤 방으로, 손님은 스냅샷의 이 값을 믿는다. */
  ended(s: S): boolean;
  /** 한 판의 입력 자리 수(선수 수). 스냅샷의 inputs 길이와 예측기의 입력 벌 크기. */
  slots(config: C): number;
  /** 그 자리를 뛰는 사람의 명단 번호(num), 봇 자리면 null. 세 군데가 이것 하나로 된다 —
   *  손님이 "내 자리"를 찾고(방장은 자리 배정을 보내지 않는다), 한마디가 진짜 그 사람 자리에서 나왔는지 보고, 사람 수로 입력 간격을 정한다. */
  slotNum(config: C, slot: number): number | null;
  /** 단계 이름(예: 킥오프·경기·골·끝). 방장은 단계가 바뀐 틱에 스냅샷을 바로 한 번 더 보내고,
   *  예측기는 단계가 바뀌는 틱에서 멈춘다 — 점수·골·끝은 스냅샷만 믿게(예측이 먼저 "골"을 띄우지 않게). */
  phase(s: S): string;
  /** 예측이 넘어가도 되는 단계 전환(from → to). 없으면 모든 전환에서 멈춘다.
   *  2D 경기의 킥오프 → 경기 중처럼 점수·시계에 영향이 없고, 얼리면 굳어 보이는 전환만 true. */
  predictsAcross?(from: string, to: string): boolean;
  /** 이 입력 변화는 간격을 기다리지 말고 바로 보낸다(예: 킥을 누르거나 뗀 순간). 없으면 모든 변화가 간격을 지킨다. */
  urgent?(prevQ: number, q: number): boolean;
  /** 봇 입력(순수). 없으면 봇·끊긴 손님 자리는 idle. */
  botInput?(state: S, config: C, slot: number): I;
  /** 그리기용 몸 목록과 그 반대(순수). 있으면 세션이 틱 사이를 섞고 스냅샷 보정을 0.1초에 걸쳐 숨기며,
   *  손님 화면은 "몸은 예측, 나머지(점수·시계·단계)는 스냅샷"으로 조립된다. 없으면 그 상태를 그대로 그린다.
   *  get 이 돌려주는 순서와 개수는 같은 판 안에서 늘 같아야 한다.
   *  jump·snap(있으면) = 그 게임 좌표 단위의 "섞지 않을 한 틱 이동"·"따라가지 않고 바로 맞출 보정" 한계 — 없으면 2D 경기 값(120·90, 논리 단위).
   *  3D 경기처럼 단위가 m 인 게임이 쓴다(2026-11-07 4단계 — 2D 값이면 36m 경기장의 킥오프 재배치가 미끄러져 보인다).
   *  몸에 z(높이)가 있으면 틱 사이 섞기가 z 도 섞는다. */
  bodies?: { get(s: S): Point[]; set(s: S, bodies: Point[]): S; jump?: number; snap?: number };
  /** 스냅샷에 실을 모양과 그 반대(2026-11-07 4단계, 선택). 있으면 방장은 pack(state) 를 보내고, 손님은 unpack 으로 되돌린 뒤 okState 로 본다.
   *  왜: 3D 경기 상태는 선수마다 칸이 많아 그대로 보내면 5대5 한 건이 4KB 를 넘는다 — 이름표(키)를 빼고 줄로 적어 절반으로.
   *  지키는 선: 잃는 게 없어야 한다 — unpack(pack(s)) 는 s 와 같은 값(그래서 step 결과도 같다). pack 은 객체를 돌려준다(parseMsg 가 배열을 거른다).
   *  unpack 은 바깥에서 온 값을 받으니 모양이 틀리면 던지지 말고 null. */
  pack?(s: S): Record<string, unknown>;
  /** 빈 사람 자리에 넣을 입력(2026-11-07 리뷰 #2, 선택) — 등록부 absent 가 'idle' 일 때 방장이 그 자리에 이걸 넣는다(없으면 idle).
   *  입력 정수(encode)로 스냅샷 inputs 에 실려 가므로 손님 예측도 같은 입력을 본다. 게임이 "나감"을 알아야 할 때(프리킥: 그 차기를 바로 넘김,
   *  드리블: 결과에 나감 표시) idle 과 다른 코드 하나를 둔다. */
  absentInput?: I;
  unpack?(packed: unknown, config: C): S | null;
};

/** 등록부에 담을 때의 모양(게임마다 C·S·I 가 달라 한 목록에 넣으려면 풀어 둔다). */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
export type AnyAdapter = GameAdapter<any, any, any>;
